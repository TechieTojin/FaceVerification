"""Test-only operations for Playwright (time travel that a browser cannot perform).

Refuses to run unless APP_ENV=test.

    python -m backend.tests.e2e_ops expire-pairing <pairing id>
    python -m backend.tests.e2e_ops notify-many <email> <count>
"""
from __future__ import annotations

import os
import sys
from datetime import datetime, timedelta


def main(argv: list[str]) -> int:
    if os.environ.get("APP_ENV") != "test":
        print("e2e_ops refuses to run unless APP_ENV=test", file=sys.stderr)
        return 2
    from backend.database import SessionLocal
    from backend.models.pairing import CapturePairing
    db = SessionLocal()
    try:
        if argv[:1] == ["expire-pairing"] and len(argv) == 2:
            n = db.query(CapturePairing).filter(CapturePairing.id == argv[1]).update(
                {"expires_at": datetime.utcnow() - timedelta(seconds=1)})
            db.commit()
            print(f"expired {n}")
            return 0 if n == 1 else 1
        if argv[:1] == ["notify-many"] and len(argv) == 3:
            from backend.models.organization import Membership
            from backend.models.user import User
            from backend.services import notification_service
            user = db.query(User).filter(User.email == argv[1]).one()
            org_id = db.query(Membership).filter(Membership.user_id == user.id).first().organization_id
            for i in range(int(argv[2])):
                notification_service.notify(db, org_id, user.id, "VERIFICATION_COMPLETED",
                                            f"Synthetic notification {i + 1} with a deliberately long title to test wrapping",
                                            "Generated by the end-to-end suite to exercise long lists.", link="/history")
            db.commit()
            return 0
        print(__doc__, file=sys.stderr)
        return 2
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
